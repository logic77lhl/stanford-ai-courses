#!/usr/bin/env python3
"""Create per-course translation packets for the English layer.

Each packet separates:

  official      English facts from ExploreCourses — do NOT translate
  editorial_zh  the Chinese notes that actually need translating

This makes the "the original is already English" point explicit: the facts are
reused as-is, only the editorial layer is translated.

Usage:
    python scripts/i18n_packet.py            # all untranslated core courses
    python scripts/i18n_packet.py --limit 8  # next batch only

Writes:
    data/i18n/queue/<slug>.json
    data/i18n/queue/README.md
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
EN_DIR = DATA / "i18n" / "en"
QUEUE = DATA / "i18n" / "queue"

RULES = [
    "The `official` block is already English. Reuse it; do not retranslate it.",
    "Translate only `editorial_zh`. Keep the same number of topic bullets.",
    "Keep course codes, people, libraries, and acronyms unchanged; see glossary.keep_as_is.",
    "Preserve hedges: 通常 -> typically, 可以 -> can, 建议 -> consider / should.",
    "Do not invent numbers, dates, prerequisites, or facts.",
    "If the Chinese note conflicts with the official description, follow the official description and flag it in `note`.",
    "Write English only. No CJK characters in any field.",
    "Set `status` to `draft` and `updated` to today's date.",
]


def load_json(path: Path):
    return json.loads(path.read_text(encoding="utf-8"))


def units(course: dict) -> str:
    lo, hi = course.get("units_min", ""), course.get("units_max", "")
    if not lo:
        return "—"
    return lo if lo == hi else f"{lo}–{hi}"


def main() -> None:
    limit = None
    if "--limit" in sys.argv:
        limit = int(sys.argv[sys.argv.index("--limit") + 1])

    ui = load_json(DATA / "i18n" / "ui.en.json")
    catalog = {c["id"]: c for c in load_json(DATA / "catalog.json")}
    courses: list[dict] = []
    for path in sorted((DATA / "courses").glob("*.json")):
        courses.extend(load_json(path))

    QUEUE.mkdir(parents=True, exist_ok=True)
    pending = []
    for c in courses:
        if (EN_DIR / f"{c['slug']}.json").exists():
            continue
        cat = catalog[c["id"]]
        packet = {
            "slug": c["slug"],
            "id": c["id"],
            "category_zh": c["cat"],
            "category_en": ui["categories"].get(c["cat"], c["cat"]),
            "official": {
                "title": cat["title"],
                "description": cat.get("description", ""),
                "units": units(cat),
                "terms": cat.get("terms", []),
                "grading": cat.get("grading", ""),
                "instructors": cat.get("instructors_pi") or cat.get("instructors") or [],
            },
            "editorial_zh": {
                "one": c["one"],
                "pos": c["pos"],
                "topics": c.get("topics", []),
                "prereq": c.get("prereq", ""),
                "assess": c.get("assess", ""),
                "who": c.get("who", ""),
                "tips": c.get("tips", ""),
                "note": c.get("note", ""),
            },
            "target_file": f"data/i18n/en/{c['slug']}.json",
            "rules": RULES,
            "glossary": "data/i18n/glossary.json",
            "ui": "data/i18n/ui.en.json",
        }
        (QUEUE / f"{c['slug']}.json").write_text(
            json.dumps(packet, ensure_ascii=False, indent=2) + "\n",
            encoding="utf-8",
            newline="\n",
        )
        pending.append(c["id"])
        if limit and len(pending) >= limit:
            break

    (QUEUE / "README.md").write_text(
        "# Translation queue\n\n"
        "Generated by `scripts/i18n_packet.py`. Not committed (see `.gitignore`).\n\n"
        "Each packet has two blocks:\n\n"
        "- `official`: English facts from ExploreCourses. **Reuse, do not retranslate.**\n"
        "- `editorial_zh`: the Chinese notes that need translating.\n\n"
        "Workflow:\n\n"
        "1. Translate `editorial_zh` into `target_file`.\n"
        "2. Keep the same number of `topics`; keep codes and names unchanged.\n"
        "3. Run `python scripts/build_i18n.py && python scripts/i18n_check.py`.\n"
        "4. Review the English page, then flip `status` to `reviewed`.\n",
        encoding="utf-8",
        newline="\n",
    )

    total = len(courses)
    done = total - len([c for c in courses if not (EN_DIR / f"{c['slug']}.json").exists()])
    print(f"packets written: {len(pending)} (coverage {done}/{total})")
    for cid in pending:
        print(f"  {cid}")


if __name__ == "__main__":
    main()
